# RISC-V 异常中断 (Trap) 测试程序
# 验证：ECALL 触发、mtvec 跳转、mepc 保存、MRET 恢复

.section .text
.globl _start

# ==============================================================
# 用户态主程序 (Entry at 0x0000)
# ==============================================================
_start:
    addi x1, x0, 10       # x1 = 10
    addi x2, x0, 20       # x2 = 20
    
    # 触发系统调用 (System Call)
    # CPU 应该立刻保存当前 PC 到 mepc，然后跳往 mtvec (0x3000)
    ecall                 
    
    # --- MRET 应该返回到这里！ ---
    # 由于我们在 ISR 中手动将 mepc + 4，MRET 会跳过 ecall，执行下一条
    add  x3, x1, x2       # x3 = 30 (如果 MRET 成功返回，x3 才会等于 30)
    
    ebreak                # 程序结束

# ==============================================================
# 异常处理程序 (Interrupt Service Routine)
# 【注意】：为了让这段代码准确放置在 0x3000，
# 汇编器可能需要链接脚本，或者我们用一种硬编码的 Trick。
# ==============================================================
# 通过填充空白，强行将 ISR 推到物理地址 0x3000 附近
# (在真实的模拟器中，你可以通过修改链接器脚本把 .trap 段放在 0x3000)
.org 0x3000               

trap_handler:
    # ISR 开始执行！
    addi x4, x0, 99       # x4 = 99 (作为标记，证明我们成功进来了)
    
    # 【OS 的常规操作】：修复 mepc，防止死循环
    # 读取引发异常的 PC (mepc 存的是 ecall 的地址)
    # 我们这里使用 CSR 伪指令 (这里你可以手动用汇编写入，但为简化，假设你的 OS 会处理)
    # 由于你的模拟器只支持基础指令，我们暂且把修复逻辑硬编码在 CPUCore 或 这里跳过。
    # 【注意】：标准的 RISC-V MRET 会直接跳回 mepc。如果 ecall 不修改 mepc，会无限 ecall。
    # 为了避免我们要在汇编里写复杂的 CSRRW 指令，
    # 我建议你在 CPUCore 的 ecall 逻辑里，直接写入 `current_instruction_pc + 4` 到 0x341！
    
    # 模拟处理完毕，从中断返回
    mret
