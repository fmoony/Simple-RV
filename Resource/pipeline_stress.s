# RISC-V 32I 综合流水线压力测试
# 目标：测试同周期 RAW 旁路、跨周期 RAW 旁路、Load-Use 停顿、连续访存结构冒险、分支预测冲刷

.section .text
.globl _start

_start:
    # ==============================================================
    # 阶段 1: ALU RAW 数据冒险与同周期旁路极限测试 (Intra-cycle Forwarding)
    # ==============================================================
    lui x1, 0x00001        # x1 = 0x1000
    addi x1, x1, 0x234     # x1 = 0x1234
    add x2, x1, x1         # x2 = 0x2468 (RAW 依赖 x1，测试 EX-EX 前推)
    sub x3, x2, x1         # x3 = 0x1234 (RAW 依赖 x2, 跨周期依赖 x1)
    or  x4, x2, x3         # x4 = 0x367C (0x2468 | 0x1234)
    and x5, x4, x1         # x5 = 0x1234 (0x367C & 0x1234)

    # ==============================================================
    # 阶段 2: 内存结构冲突与 Load-Use 停顿测试 (Memory Hazards)
    # ==============================================================
    lui x6, 0x00004        # 内存基址 x6 = 0x4000
    sw x2, 0(x6)           # M[0x4000] = 0x2468
    sw x3, 4(x6)           # M[0x4004] = 0x1234 (【测试点】连续 SW 必须被打断为单发射)
    lw x7, 0(x6)           # x7 = 0x2468
    
    # 【高危测试点】紧接着 LW 使用 x7，IssueUnit 必须在这里拦截并产生 Stall 气泡
    add x8, x7, x5         # x8 = 0x369C (0x2468 + 0x1234)
    
    lw x9, 4(x6)           # x9 = 0x1234
    sub x10, x7, x9        # x10 = 0x1234 (0x2468 - 0x1234)

    # ==============================================================
    # 阶段 3: 复杂控制流与分支流水线冲刷 (Control Hazards)
    # ==============================================================
    addi x11, x0, 5        # 循环变量 x11 = 5
    addi x12, x0, 0        # 累加器 x12 = 0

loop_start:
    beq x11, x0, loop_end  # 如果 x11 == 0，跳出循环
    add x12, x12, x11      # x12 += x11
    addi x11, x11, -1      # x11--
    
    # 嵌套一个必跳转的分支，作为 Unconditional Jump 使用
    # 【测试点】这里每次执行都会触发 Pipeline Flush，废弃误取的指令
    blt x11, x12, loop_start 

loop_end:
    # 循环结束，此时 x12 应该是 5+4+3+2+1 = 15 (0xF)
    sw x12, 8(x6)          # 将累加结果存入 M[0x4008]

    # ==============================================================
    # 阶段 4: 双发射并发极值测试 (Parallel Execution)
    # ==============================================================
    # 以下两对指令互相之间完全没有数据依赖，也没有结构冲突
    # 你的 IssueUnit 应该以完美的双发射 (Dual-Issue) 放行它们
    lui x13, 0x0000A
    lui x14, 0x0000B
    addi x13, x13, 1       # x13 = 0xA001
    addi x14, x14, 2       # x14 = 0xB002
    
    ebreak                 # 测试结束