# RV32I 完整指令集极限验证测试 (ISA Completion Stress Test)
# 验证：U型/J型PC计算、移位逻辑、有符号/无符号比较、子字访存与扩展

.section .text
.globl _start

_start:
    # ==============================================================
    # 阶段 1: U-Type 测试 (LUI, AUIPC)
    # ==============================================================
    lui x1, 0x12345        # x1 = 0x12345000
auipc_label:
    # AUIPC 会将立即数左移 12 位后加上当前 PC。
    # 假设当前 PC = 0x04，则 x2 = 0x04 + 0x1000 = 0x1004
    auipc x2, 0x00001      

    # ==============================================================
    # 阶段 2: 移位与符号逻辑 (Shifts & Compares)
    # ==============================================================
    addi x3, x0, -16       # x3 = 0xFFFFFFF0 (-16)
    addi x4, x0, 15        # x4 = 0x0000000F (15)

    slli x5, x3, 4         # x5 = 0xFFFFFFF0 << 4 = 0xFFFFFF00
    srai x6, x5, 4         # x6 = 0xFFFFFF00 算术右移 4 = 0xFFFFFFFF (-1，高位补1)
    srli x7, x5, 4         # x7 = 0xFFFFFF00 逻辑右移 4 = 0x0FFFFFFF (高位补0)

    slt  x8, x3, x4        # x8 = 1 (-16 < 15, 有符号比较为真)
    sltu x9, x3, x4        # x9 = 0 (0xFFFFFFF0 < 15, 无符号比较为假)

    # ==============================================================
    # 阶段 3: 子字访存与端序扩展 (Sub-word Memory Access)
    # ==============================================================
     lui  x10, 0x00004      # x10 = 0x4000 (内存基址)
    li   x11, 0x89ABCDEF   # 强大的 li 伪指令，汇编器会自动将其翻译为合法的 lui + addi
    
    # 写入全字 (由于是小端序，内存中 0x4000~0x4003 的分布为: EF CD AB 89)
    sw   x11, 0(x10)       
    
    # 读取测试 (极限考验译码阶段的 funct3 处理)
    lb   x12, 0(x10)       # 读出 0xEF。符号扩展后 x12 = 0xFFFFFFEF
    lbu  x13, 1(x10)       # 读出 0xCD。无符号扩展后 x13 = 0x000000CD
    lh   x14, 2(x10)       # 读出 0x89AB。符号扩展后 x14 = 0xFFFF89AB
    
    # 子字写入测试
    sh   x12, 4(x10)       # 取 x12(0xFFFFFFEF) 的低 16 位 0xFFEF 写入 0x4004
    lhu  x15, 4(x10)       # 读出 0xFFEF。无符号扩展 x15 = 0x0000FFEF

    # ==============================================================
    # 阶段 4: 绝对与间接跳转 (JAL, JALR) 与流水线冲刷
    # ==============================================================
test_jal:
    jal  x16, jump_target_1  # 相对跳转！x16 = test_jal_PC + 4 
    addi x17, x0, 99         # 【幽灵指令 1】如果冲刷失败，x17会被设为99！
    
jump_target_1:
    # 此时应该成功跳过了幽灵指令 1 (x17 必须还是 0)
    # 接下来测试 JALR (寄存器间接绝对跳转)
    # 假设上面 JAL 指令的 PC 是 0x48，那么 x16 = 0x4C。
    addi x18, x16, 16        # 计算 JALR 目标基址: x18 = 0x4C + 16 = 0x5C
    
    jalr x19, x18, 0         # 绝对跳转到 0x5C！写回返回地址 x19 = 0x58
    addi x20, x0, 99         # 【幽灵指令 2】如果被执行，x20会被设为99！
    
jump_target_2:               # 这里的物理地址恰好是 0x5C
    ebreak                   # 完美结束
